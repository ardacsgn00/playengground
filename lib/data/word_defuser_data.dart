enum DefuserType { misspelled, antonym, synonym, meaning }

class DefuserQuestion {
  final DefuserType type;

  /// Word shown on the bomb panel (null for spelling rounds).
  final String? target;

  /// The wire that must be cut.
  final String correct;

  /// Three distractor wires.
  final List<String> wrong;

  /// Extra explanation (correct spelling or false-friend note).
  final String? note;

  const DefuserQuestion({
    required this.type,
    required this.correct,
    required this.wrong,
    this.target,
    this.note,
  });
}

